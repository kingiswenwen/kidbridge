import { readFile, writeFile } from 'node:fs/promises';
import { transform } from 'esbuild';
const source = await readFile(new URL('../src/utils/racing/track.ts', import.meta.url), 'utf8');
const { code } = await transform(source, { loader: 'ts', format: 'esm' });
const { trackPath } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const path = new URL('../src/static/racing/track.svg', import.meta.url);
const d = trackPath();
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 280" preserveAspectRatio="none"><!-- Generated by scripts/generate-racing-track.mjs -->
<rect width="640" height="280" rx="30" fill="#eaf6e3"/><path d="M0 65Q140 0 280 72T640 38V0H0Z" fill="#d9f0ee"/><path d="M0 270Q130 200 300 254T640 233V280H0Z" fill="#d7ecb5"/><circle cx="553" cy="42" r="20" fill="#ffe290"/>
<path d="${d}" fill="none" stroke="#fffdf5" stroke-width="68" stroke-linecap="round"/><path id="road-center" d="${d}" fill="none" stroke="#efd3a4" stroke-width="49" stroke-linecap="round"/><path d="${d}" fill="none" stroke="#fff9e6" stroke-width="3" stroke-dasharray="12 12"/>
<g fill="#77bfa4"><ellipse cx="30" cy="78" rx="12" ry="23"/><ellipse cx="190" cy="248" rx="10" ry="20"/><ellipse cx="480" cy="56" rx="11" ry="22"/></g></svg>\n`;
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== svg) throw new Error('Run node scripts/generate-racing-track.mjs to update the track artwork');
} else await writeFile(path, svg);
